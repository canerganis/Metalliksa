/** Element with the highest wt% (first one on a tie); the single element whose M-H2O map a preset is shown with. */
export function primaryElementOf(composition: { [element: string]: number }): string {
  let best = "Fe";
  let bestWt = -1;
  for (const [el, wt] of Object.entries(composition)) {
    if (wt > bestWt) { best = el; bestWt = wt; }
  }
  return best;
}
