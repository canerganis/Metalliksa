#!/usr/bin/env python3
"""Make MatCalc open TDB files readable by pycalphad without changing any
thermodynamic parameter.

The repair is purely syntactic and every change is reported. Rules:

* MatCalc-only directives that pycalphad cannot parse and that carry no
  equilibrium thermodynamic parameter (REFERENCE_ELEMENT, ATTACH_CONTRIBUTION,
  ADD_COMPOSITION_SET) are commented out, not deleted.
* MatCalc-only kinetic parameter types (HMVA, SE; vacancy formation enthalpy and
  similar extras) are commented out. They are NOT part of the Gibbs energy model
  used by pycalphad (G, L, TC, BMAGN ...), but they are parameters, so the
  repair lists each one, counts them, and refuses (exit 2) when ``--strict`` is
  given.
* ``PARAMETER G(PHASE;CONST;0)`` (semicolon after the phase) is rewritten to the
  standard comma form ``G(PHASE,CONST;0)``.
* The malformed upper temperature limit ``6000.00.00`` is rewritten to
  ``6000.00`` (no other reading of the token exists).
* A missing terminating ``!`` before the next command keyword is inserted.
* A FUNCTION statement whose citation tag sits alone on the following line
  (``... 6000.00 N`` newline ``REF: 170 !``) gets that tag joined onto the
  statement line and ``REF: 170`` written as ``REF:170`` (pycalphad rejects the
  split form). The function expression itself is not touched.

Safety check: after repair the tool re-derives, for every retained G/L/TC/BMAGN
(and any other non-dropped) PARAMETER statement, a canonical form (whitespace
removed, the two declared rewrites undone) and requires it to equal the original
statement. Any difference aborts with exit code 3 and no output is written. The
original file is never modified; the repaired copy starts with a header citing
the origin and the ODbL/DbCL licence (share-alike applies to the copy).

Usage:
    python tools/tdb_repair.py IN.tdb OUT.tdb [--report REPORT.json] [--strict]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

COMMAND_KEYWORDS = (
    "ELEMENT", "SPECIES", "PHASE", "CONSTITUENT", "PARAMETER", "FUNCTION",
    "TYPE_DEFINITION", "DEFINE_SYSTEM_DEFAULT", "DEFAULT_COMMAND",
    "LIST_OF_REFERENCES", "ASSESSED_SYSTEMS", "REFERENCE_ELEMENT",
    "ATTACH_CONTRIBUTION", "ADD_COMPOSITION_SET",
)
DROP_DIRECTIVES = ("REFERENCE_ELEMENT", "ATTACH_CONTRIBUTION", "ADD_COMPOSITION_SET")
DROP_PARAMETER_TYPES = ("HMVA", "SE")
KEYWORD_LINE = re.compile(r"^[ \t]*(%s)\b" % "|".join(COMMAND_KEYWORDS), re.I | re.M)
PARAM_HEAD = re.compile(r"PARAMETER\s+([A-Z0-9_]+)\s*\(([^)]*)\)", re.I)
BAD_TLIMIT = re.compile(r"(?<![0-9.])(\d+\.\d+)\.(\d+)(?![0-9.])")
# "CONSTITUENT X : A : B :  > >> 1" : stray symbols after the last sublattice colon
CONSTITUENT_JUNK = re.compile(r"(:[ \t]*)(>[> \t0-9]*)[ \t]*$")
# "REF:TEST KOZE10" : a citation tag containing a blank
REF_MULTI = re.compile(r"REF:[ \t]*([A-Za-z0-9_.:-]+(?:[ \t]+[A-Za-z0-9_.:-]+)+)[ \t\n]*$", re.I)
REF_SPACE = re.compile(r"(REF:)[ \t]+", re.I)
# "273.00 273 +46000..." : a second number glued in front of the expression
STRAY_T = re.compile(r"(\)[ \t]+)(\d+(?:\.\d+)?)([ \t]+)(\d+(?:\.\d+)?)(?=[ \t]+[+\-])")
# "; 6000.00  N ; 6000.00  N" : the range terminator repeated verbatim
DUP_TAIL = re.compile(r"(;[ \t]*(\d+(?:\.\d+)?)[ \t]+N)[ \t]*;[ \t]*(\d+(?:\.\d+)?)[ \t]+N", re.I)

# FUNCTION whose "REF: 170" tag follows on its own line after the range terminator
FUNC_REF_TAIL = re.compile(
    r"([ \t]*;[ \t]*\d+(?:\.\d+)?[ \t]+[YN])[ \t]*\n[ \t]*(REF:)[ \t]*([A-Za-z0-9_.:-]+)[ \t]*$", re.I)


HEADER = """$ ---------------------------------------------------------------------------
$ SYNTACTICALLY REPAIRED COPY - generated by python/tools/tdb_repair.py
$ Origin: {origin}
$ Source file: {name} (sha256 {sha})
$ Original is MatCalc open database, (c) Erwin Povoden-Karadeniz / TU Wien,
$ made available under the Open Database License 1.0
$ (http://opendatacommons.org/licenses/odbl/1.0/); contents under the Database
$ Contents License 1.0 (http://opendatacommons.org/licenses/dbcl/1.0/).
$ This copy is an altered (derivative) database: ODbL share-alike applies.
$ Alterations (syntax only, listed in the repair report; no G/L/TC/BMAGN
$ parameter value was changed): MatCalc-only directives and extra parameter
$ types commented out with the prefix "$ [tdb_repair]", semicolon/comma and
$ temperature-limit typos fixed, missing '!' inserted, bibliography text
$ commented out; ambiguous stray tokens only if the report lists them.
$ ---------------------------------------------------------------------------
"""


class RepairRefused(Exception):
    pass


def _strip_comments(text: str) -> str:
    return re.sub(r"\$[^\n]*", "", text)


def split_statements(text: str):
    """Yield (chunk, ends_with_bang). A chunk is leading comments/space plus the
    statement body; '!' inside a $ comment is not a terminator."""
    out, start, i, n = [], 0, 0, len(text)
    while i < n:
        c = text[i]
        if c == "$":
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if c == "!":
            out.append((text[start:i], True))
            start = i + 1
        i += 1
    if start < n:
        out.append((text[start:], False))
    return out


def canon_param(body: str) -> str:
    """Canonical form used for the preservation check (declared rewrites undone)."""
    s = _strip_comments(body)
    s = re.sub(r"REF:.*$", "", s, flags=re.I | re.S)  # citation label, not a parameter value
    s = STRAY_T.sub(lambda m: m.group(1) + m.group(2), s)
    s = DUP_TAIL.sub(lambda m: m.group(1), s)
    s = re.sub(r"\s+", "", s).upper()
    s = re.sub(r"^PARAMETER([A-Z0-9_]+)\(([^;,)]*)[;,]", r"PARAMETER\1(\2,", s, count=1)
    s = BAD_TLIMIT.sub(lambda m: m.group(1), s)
    return s


def _comment_out(chunk: str, tag: str) -> str:
    lines = chunk.split("\n")
    return "\n".join(
        l if (not l.strip() or l.lstrip().startswith("$")) else "$ [tdb_repair] %s: %s" % (tag, l)
        for l in lines
    )


def repair_text(text: str, strict: bool = False, allow_ambiguous: bool = False):
    repairs: list[dict] = []
    text = text.replace("\r\n", "\n")
    chunks = split_statements(text)
    new_chunks: list[str] = []
    n_params_before = n_params_after = 0

    in_refs = False
    for chunk, banged in chunks:
        body = _strip_comments(chunk)
        stripped = body.strip()
        if re.match(r"LIST_OF_REFERENCES\b", stripped, re.I):
            in_refs = True  # bibliography free text: never touched
        if in_refs or (stripped and not banged):  # bibliography free text
            if stripped:
                nlines = len([l for l in chunk.split("\n") if l.strip() and not l.lstrip().startswith("$")])
                repairs.append({"rule": "comment-out-bibliography",
                                "detail": "%d lines of free text (references)" % nlines})
                new_chunks.append(_comment_out(chunk, "bibliography") + (
                    "\n$ [tdb_repair] (terminator removed)\n" if banged else ""))
            else:
                new_chunks.append(chunk + ("!" if banged else ""))
            continue
        if not stripped:
            new_chunks.append(chunk + ("!" if banged else ""))
            continue
        # 1. a missing '!' shows up as a second command keyword at a line start
        hits = [m for m in KEYWORD_LINE.finditer(body)]
        # offsets are relative to the comment-stripped body; map to chunk lines
        if len(hits) > 1:
            lines = chunk.split("\n")
            kw_lines = [k for k, l in enumerate(lines)
                        if not l.lstrip().startswith("$") and KEYWORD_LINE.match(l)]
            pieces, prev = [], 0
            for k in kw_lines[1:]:
                pieces.append("\n".join(lines[prev:k]))
                repairs.append({"rule": "insert-missing-terminator",
                                "detail": "inserted '!' before line starting: " + lines[k].strip()[:60]})
                prev = k
            pieces.append("\n".join(lines[prev:]))
            sub = [(p, True) for p in pieces[:-1]] + [(pieces[-1], banged)]
        else:
            sub = [(chunk, banged)]
        for idx, (piece, pb) in enumerate(sub):
            fixed_piece = _fix_statement(piece, pb, repairs, allow_ambiguous)
            new_chunks.append(fixed_piece + ("\n" if idx < len(sub) - 1 else ""))
            pbody = _strip_comments(piece)
            if re.match(r"\s*PARAMETER\b", pbody, re.I):
                n_params_before += 1
    result = "".join(new_chunks)
    return result, repairs, n_params_before


def _fix_statement(piece: str, banged: bool, repairs: list, allow_ambiguous: bool = False) -> str:
    bang = "!" if banged else ""
    body = _strip_comments(piece)
    head = body.split(None, 1)[0].upper() if body.strip() else ""
    if head in DROP_DIRECTIVES:
        repairs.append({"rule": "drop-directive", "detail": " ".join(body.split())[:100]})
        return _comment_out(piece, "unsupported directive") .rstrip() + ("\n$ [tdb_repair] (terminator removed)\n" if banged else "")
    if head == "CONSTITUENT":
        cm = CONSTITUENT_JUNK.search(piece)
        if cm:
            repairs.append({"rule": "constituent-trailing-junk",
                            "detail": "removed %r after the last sublattice of: %s" % (
                                cm.group(2).strip(), " ".join(body.split())[:60])})
            piece = piece[:cm.start(2)] + piece[cm.end(2):]
        return piece + bang
    if head == "FUNCTION":
        fm = FUNC_REF_TAIL.search(piece)
        if fm:
            piece = piece[:fm.start()] + fm.group(1) + " REF:" + fm.group(3)
            repairs.append({"rule": "function-ref-join",
                            "detail": "joined trailing REF tag onto the FUNCTION line and removed the blank after REF: (REF:%s) in: %s"
                                      % (fm.group(3), " ".join(body.split())[:50])})
        return piece + bang
    if head == "PARAMETER":
        m = PARAM_HEAD.search(body)
        if not m:
            return piece + bang
        ptype = m.group(1).upper()
        if ptype in DROP_PARAMETER_TYPES:
            repairs.append({"rule": "drop-matcalc-parameter", "ptype": ptype,
                            "detail": " ".join(body.split())[:100]})
            return _comment_out(piece, "MatCalc-only parameter %s" % ptype).rstrip() + (
                "\n$ [tdb_repair] (terminator removed)\n" if banged else "")
        orig = piece
        # semicolon after the phase name inside the head: G(PH;CONST;0) -> G(PH,CONST;0)
        hm = PARAM_HEAD.search(piece)
        inner = hm.group(2)
        if "," not in inner and inner.count(";") == 2:
            new_inner = inner.replace(";", ",", 1)
            piece = piece[:hm.start(2)] + new_inner + piece[hm.end(2):]
            repairs.append({"rule": "semicolon-to-comma", "detail": "%s(%s) -> (%s)" % (ptype, inner, new_inner)})
        def _t(mm):
            repairs.append({"rule": "fix-temperature-limit", "detail": "%s -> %s" % (mm.group(0), mm.group(1))})
            return mm.group(1)
        piece = BAD_TLIMIT.sub(_t, piece)
        if REF_SPACE.search(piece):
            piece = REF_SPACE.sub(r"\1", piece)
            repairs.append({"rule": "ref-tag-space", "detail": "removed blank after REF:"})
        rm = REF_MULTI.search(piece)
        if rm:
            piece = piece[:rm.start()] + "REF:" + "_".join(rm.group(1).split()) + piece[rm.end():]
            repairs.append({"rule": "ref-tag-blank", "detail": "REF tag with blank joined by '_': " + rm.group(1)})
        amb = bool(STRAY_T.search(piece) or DUP_TAIL.search(piece))
        if amb:
            if not allow_ambiguous:
                raise RepairRefused("ambiguous construct (stray number / duplicated range tail) in: "
                                    + " ".join(orig.split())[:120] + "; rerun with --allow-ambiguous to accept")
            def _s(mm):
                repairs.append({"rule": "ambiguous-stray-number", "assumption": True,
                                "detail": "%s: dropped stray %s after lower limit %s" % (ptype, mm.group(4), mm.group(2))})
                return mm.group(1) + mm.group(2)
            piece = STRAY_T.sub(_s, piece)
            def _d(mm):
                repairs.append({"rule": "ambiguous-duplicate-range-tail", "assumption": True,
                                "detail": "%s: dropped repeated '; %s N'" % (ptype, mm.group(3))})
                return mm.group(1)
            piece = DUP_TAIL.sub(_d, piece)
        if canon_param(piece) != canon_param(orig):
            raise RepairRefused("parameter statement would change: " + " ".join(orig.split())[:120])
        return piece + bang
    return piece + bang


def _retained_params(text: str) -> list[str]:
    """Canonical forms of all PARAMETER statements except the dropped MatCalc
    types, extracted without relying on '!' so a missing terminator cannot hide one."""
    body = _strip_comments(text)
    cut = re.search(r"^[ \t]*LIST_OF_REFERENCES\b", body, re.I | re.M)
    if cut:
        body = body[:cut.start()]
    pat = re.compile(
        r"^[ \t]*PARAMETER\b.+?(?=^[ \t]*(?:%s)\b|!)" % "|".join(COMMAND_KEYWORDS),
        re.I | re.M | re.S)
    out = []
    for m in pat.finditer(body):
        hm = PARAM_HEAD.search(m.group(0))
        if hm and hm.group(1).upper() in DROP_PARAMETER_TYPES:
            continue
        out.append(canon_param(m.group(0)))
    return out


def repair_file(src: Path, dst: Path, origin: str, strict: bool = False, report: Path | None = None,
                allow_ambiguous: bool = False):
    import hashlib
    raw = src.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if src.resolve() == dst.resolve():
        raise RepairRefused("output path equals input path; the original must stay untouched")
    text = raw.decode("utf-8", errors="replace")
    fixed, repairs, nparams = repair_text(text, strict, allow_ambiguous)
    dropped = [r for r in repairs if r["rule"] == "drop-matcalc-parameter"]
    if strict and dropped:
        raise RepairRefused("strict mode: %d MatCalc-only parameters would be dropped" % len(dropped))
    # independent preservation check on the retained parameter statements
    kept_orig = _retained_params(text.replace("\r\n", "\n"))
    kept_new = _retained_params(fixed)
    if kept_orig != kept_new:
        raise RepairRefused("retained parameter statements differ from the original (%d vs %d)"
                            % (len(kept_orig), len(kept_new)))
    header = HEADER.format(origin=origin, name=src.name, sha=sha)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(header + fixed, encoding="utf-8", newline="\n")
    summary: dict = {}
    for r in repairs:
        summary[r["rule"]] = summary.get(r["rule"], 0) + 1
    rep = {"source": str(src), "sourceSha256": sha, "output": str(dst), "origin": origin,
           "parametersRetained": len(kept_new), "ruleCounts": summary,
           "droppedMatcalcParameterTypes": sorted({r["ptype"] for r in dropped}),
           "repairs": repairs}
    if report:
        report.write_text(json.dumps(rep, indent=1), encoding="utf-8")
    return rep


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("src", type=Path)
    ap.add_argument("dst", type=Path)
    ap.add_argument("--origin", default="MatCalc open databases, https://www.matcalc.at/index.php/databases/open-databases")
    ap.add_argument("--report", type=Path)
    ap.add_argument("--allow-ambiguous", action="store_true",
                    help="accept the two ambiguous repairs (stray number, repeated range tail); listed as assumptions")
    ap.add_argument("--strict", action="store_true",
                    help="refuse (exit 2) if any MatCalc-only parameter would have to be dropped")
    a = ap.parse_args(argv)
    try:
        rep = repair_file(a.src, a.dst, a.origin, a.strict, a.report, a.allow_ambiguous)
    except RepairRefused as exc:
        print("REFUSED:", exc, file=sys.stderr)
        return 2 if "strict" in str(exc) else 3
    print(json.dumps({k: v for k, v in rep.items() if k != "repairs"}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
